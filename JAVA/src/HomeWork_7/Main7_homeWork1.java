package HomeWork_7;

public class Main7_homeWork1 {

//   МЕТОД УМНОЖЕНИЕ

    public static double multiply(double a, double b) {
        return a * b;
    }

    //    МЕТОД Сложение (sum)
    public static int sum(int a, int b) {
        return a + b;
    }

    //    МЕТОД Вычитание (subtract)
    public static long subtract(long a, long b) {
        return a - b;
    }

    //    Метод ДЕЛЕНИЕ divide()
    public static double divide(double a, double b) {
        return a / b;
    }


    static void main() {
        System.out.println( subtract(21, 2) );
        System.out.println(multiply(4, 6));
        System.out.println(sum(35, 6) + 7777);
        System.out.println(divide(36, 2) + 1);
    }


}







